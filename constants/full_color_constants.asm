; Audit-only natural VBlank cycle authority.  These are CPU T-cycles measured
; independently of descriptor byte/write reservations.  Geometry classes add
; the per-cell cost to the fixed validation/publication base.
; Provisional physical ceiling for the forced calibrated capture: the fixed
; 9,120-cycle VBlank deadline less one measured 912-cycle scanline guard. The
; final scheduler authority is derived from that capture's fixed overhead.
DEF FULL_COLOR_PHASE5_VBLANK_SCHEDULER_BUDGET EQU 8208
; Calibrated CPU T-cycle authority separates the invariant owned-frame route
; from each complete visible unit.  The base is reserved before any unit; a
